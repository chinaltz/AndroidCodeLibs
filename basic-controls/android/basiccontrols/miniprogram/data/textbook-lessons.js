function getUnits(grade, volume) {
  const book = LESSON_CATALOG[grade] && LESSON_CATALOG[grade][volume];
  if (!book) return [];
  return book.units.map(function(u) {
    return { unitNo: u.unitNo, title: u.title };
  });
}

function getLessons(grade, volume, unitNo) {
  var book = LESSON_CATALOG[grade] && LESSON_CATALOG[grade][volume];
  if (!book) return [];
  var units = unitNo == null
    ? book.units
    : book.units.filter(function(u) { return u.unitNo === unitNo; });
  var lessons = [];
  units.forEach(function(u) {
    u.lessons.forEach(function(l) { lessons.push(l); });
  });
  return lessons;
}

function getCharacters(grade, volume, unitNo, lessonNos) {
  var allLessons = getLessons(grade, volume, unitNo);
  var lessons = lessonNos == null
    ? allLessons
    : allLessons.filter(function(l) { return lessonNos.indexOf(l.lessonNo) >= 0; });
  var seen = {};
  var result = [];
  lessons.forEach(function(l) {
    (l.characters || []).forEach(function(c) {
      if (!seen[c]) { seen[c] = true; result.push(c); }
    });
  });
  return result;
}

function getWords(grade, volume, unitNo, lessonNos) {
  var allLessons = getLessons(grade, volume, unitNo);
  var lessons = lessonNos == null
    ? allLessons
    : allLessons.filter(function(l) { return lessonNos.indexOf(l.lessonNo) >= 0; });
  var seen = {};
  var result = [];
  lessons.forEach(function(l) {
    (l.words || []).forEach(function(w) {
      if (!seen[w]) { seen[w] = true; result.push(w); }
    });
  });
  return result;
}

/**
 * 按选字顺序为每个字选择一个课内词，尽量避免重复词语，
 * 同一个词命中多个所选字时合并 unknownChars。
 * 返回: [{ word: '天地', unknownChars: ['天','地'] }, ...]
 */
function getWordsByChars(grade, volume, unitNo, lessonNos, charSet) {
  var allWords = getWords(grade, volume, unitNo, lessonNos);
  var selectedChars = charSet || [];
  var usedWords = {};
  var result = [];
  selectedChars.forEach(function(character) {
    var word = allWords.find(function(candidate) {
      return !usedWords[candidate] && candidate.indexOf(character) >= 0;
    });
    if (!word) {
      word = allWords.find(function(candidate) {
        return candidate.indexOf(character) >= 0;
      });
    }
    if (!word) return;
    var existing = result.find(function(item) { return item.word === word; });
    if (existing) {
      if (existing.unknownChars.indexOf(character) < 0) existing.unknownChars.push(character);
      return;
    }
    usedWords[word] = true;
    result.push({ word: word, unknownChars: [character] });
  });
  return result;
}

